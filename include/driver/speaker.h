/**
 * =========================================================================
 * speaker.h - PC 扬声器驱动接口
 *
 * 硬件背景：
 *   PC 内置扬声器（PC Speaker）通过 PIT（可编程间隔定时器）通道 2
 *   驱动。控制原理很简单：
 *     1. 设置 PIT 通道 2 的模式和计数值，产生特定频率的方波
 *     2. 将扬声器门控位（端口 0x61 的 bit 0 和 bit 1）置位，
 *        让方波信号通过到扬声器
 *     3. 等待一段时间后复位门控位关闭声音
 *
 * 注意：这个扬声器只能产生单音调方波，不能播放 WAV/MP3 等多媒体音频。
 * 它的典型用途是 BIOS 报错 Beep、内核启动自检提示音等。
 * =========================================================================
 */

#ifndef SPEAKER_H
#define SPEAKER_H

#include <stdint.h>

/**
 * speaker_beep - 让 PC 扬声器发出指定频率和持续时间的蜂鸣音
 * @freq_hz:     频率（Hz），如 800 表示 800Hz 中音
 * @duration_ms: 持续时间（毫秒）
 *
 * 实现方式：
 *   1. 计算 PIT 分频系数 = 1193180 / freq_hz
 *   2. 设置 PIT 通道 2（端口 0x42）为分频模式 3（方波生成器）
 *   3. 启用扬声器（端口 0x61 的 bit 0 和 1 置位）
 *   4. 忙等待指定毫秒数
 *   5. 关闭扬声器
 */
void speaker_beep(uint32_t freq_hz, uint32_t duration_ms);

/**
 * speaker_off - 强制关闭 PC 扬声器
 * 复位端口 0x61 的 bit 0 和 bit 1
 */
void speaker_off(void);

#endif
